#!/usr/bin/env python3
"""Copy the screensaver's live preview into this site as screensaver/preview.html.

The preview is the same three.js bundle the Windows .scr runs, built as one self-contained HTML file by the
screensaver repo (froglet-studio/cosmic-shore-screensaver, `npm run build:single`). It makes no network
calls once loaded. This script wraps that file in a full HTML document and writes it here; the page has no
front matter, so Jekyll copies it as it is.

    python3 tools/sync_screensaver_preview.py [--repo ../cosmic-shore-screensaver] [--no-build]

Run it after a screensaver release that changes the look, and commit screensaver/preview.html.
"""
import argparse
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "screensaver" / "preview.html"

HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<link rel="canonical" href="https://www.froglet.games/screensaver/">
<link rel="icon" type="image/png" sizes="32x32" href="/assets/branding/favicon-32.png">
<!-- Generated by tools/sync_screensaver_preview.py from cosmic-shore-screensaver {rev}. Do not edit by hand. -->
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default=str(ROOT.parent / "cosmic-shore-screensaver"))
    ap.add_argument("--no-build", action="store_true", help="use the repo's existing dist-single/ output")
    a = ap.parse_args()
    repo = pathlib.Path(a.repo).resolve()
    if not (repo / "package.json").exists():
        sys.exit(f"screensaver repo not found at {repo}")
    if not a.no_build:
        subprocess.run(["npm", "run", "-s", "build:single"], cwd=repo, check=True)
    src = repo / "dist-single" / "cosmic-shore-screensaver.html"
    rev = subprocess.run(["git", "-C", str(repo), "describe", "--tags", "--always"],
                         capture_output=True, text=True).stdout.strip() or "unknown"
    body = src.read_text(encoding="utf-8")
    OUT.write_text(HEAD.format(rev=rev) + body + "</html>\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1e6:.2f} MB) from {rev}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
